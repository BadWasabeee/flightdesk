#!/bin/sh
# Rebuilds Shared/Resources/runways.csv from OurAirports runways.csv (public domain):
# open runways with coordinates for both ends, at airports listed in Shared/Resources/airports.csv.
#
# Output columns: icao,le_ident,le_lat,le_lon,le_hdg,he_ident,he_lat,he_lon,he_hdg,length_ft,elevation_ft
# Headings are degrees true, computed from the end coordinates when the source omits one or
# disagrees with them by more than 3 degrees (some rows carry magnetic headings). Elevation is the
# runway's, else the airport's (OurAirports airports.csv).
#
# Usage: scripts/update-runways.sh
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
AIRPORTS="$ROOT/Shared/Resources/airports.csv"
OUT="$ROOT/Shared/Resources/runways.csv"
SOURCE="https://davidmegginson.github.io/ourairports-data/runways.csv"
ELEVATIONS="https://davidmegginson.github.io/ourairports-data/airports.csv"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir "$WORK/download"

curl --fail --silent --show-error --location --proto '=https' --max-time 120 \
    --output "$WORK/download/runways.csv" "$SOURCE"
curl --fail --silent --show-error --location --proto '=https' --max-time 120 \
    --output "$WORK/download/airports.csv" "$ELEVATIONS"

cat > "$WORK/build.py" <<'PY'
import csv, math, sys

source, elevations_path, airports_path, out_path, source_url, elevations_url, date = sys.argv[1:8]

with open(airports_path, encoding="utf-8") as f:
    icaos = {line.split(",")[1] for line in f if line.count(",") >= 4}

def num(s):
    try:
        v = float(s)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None

with open(elevations_path, encoding="utf-8", newline="") as f:
    field_elevation = {r["ident"].strip().upper(): num(r["elevation_ft"]) for r in csv.DictReader(f)}

def bearing(la1, lo1, la2, lo2):
    p1, p2, dl = math.radians(la1), math.radians(la2), math.radians(lo2 - lo1)
    y = math.sin(dl) * math.cos(p2)
    x = math.cos(p1) * math.sin(p2) - math.sin(p1) * math.cos(p2) * math.cos(dl)
    return (math.degrees(math.atan2(y, x)) + 360) % 360

def heading(listed, computed):
    """The listed true heading, unless it is missing or disagrees with the coordinates."""
    if listed is None or abs((listed - computed + 540) % 360 - 180) > 3:
        return computed
    return listed

def ident(s):
    """Runway designator ("28C", "01L", "36") or "" for helipads and malformed values."""
    s = (s or "").strip().upper()
    return s if s.isalnum() and not s.startswith("H") else ""

rows = []
with open(source, encoding="utf-8", newline="") as f:
    for r in csv.DictReader(f):
        icao = r["airport_ident"].strip().upper()
        if icao not in icaos or r["closed"].strip() == "1":
            continue
        le_lat, le_lon = num(r["le_latitude_deg"]), num(r["le_longitude_deg"])
        he_lat, he_lon = num(r["he_latitude_deg"]), num(r["he_longitude_deg"])
        le_id, he_id = ident(r["le_ident"]), ident(r["he_ident"])
        if None in (le_lat, le_lon, he_lat, he_lon) or not le_id or not he_id:
            continue
        if (le_lat, le_lon) == (he_lat, he_lon):
            continue
        le_hdg = heading(num(r["le_heading_degT"]), bearing(le_lat, le_lon, he_lat, he_lon))
        he_hdg = heading(num(r["he_heading_degT"]), bearing(he_lat, he_lon, le_lat, le_lon))
        length = num(r["length_ft"])
        elev = next((e for e in (num(r["le_elevation_ft"]), num(r["he_elevation_ft"]),
                                 field_elevation.get(icao)) if e is not None), None)
        rows.append([icao, le_id, "%.6f" % le_lat, "%.6f" % le_lon, "%.1f" % (le_hdg % 360),
                     he_id, "%.6f" % he_lat, "%.6f" % he_lon, "%.1f" % (he_hdg % 360),
                     "" if length is None else str(int(round(length))),
                     "" if elev is None else str(int(round(elev)))])

rows.sort(key=lambda r: (r[0], r[1]))
with open(out_path, "w", encoding="utf-8", newline="") as f:
    f.write("# Runways at airports in airports.csv, from OurAirports runways.csv (public domain)\n")
    f.write("# %s (elevation fallback: %s)\n" % (source_url, elevations_url))
    f.write("# Generated by scripts/update-runways.sh on %s\n" % date)
    f.write("# icao,le_ident,le_lat,le_lon,le_hdg,he_ident,he_lat,he_lon,he_hdg,length_ft,elevation_ft\n")
    w = csv.writer(f, lineterminator="\n")
    w.writerows(rows)
print("%d runways at %d airports" % (len(rows), len({r[0] for r in rows})))
PY

python3 -I "$WORK/build.py" "$WORK/download/runways.csv" "$WORK/download/airports.csv" "$AIRPORTS" "$OUT.tmp" "$SOURCE" "$ELEVATIONS" "$(date -u +%Y-%m-%d)"
mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
