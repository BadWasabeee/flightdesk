// Runways at airports with scheduled service, bundled with the app, the widget and the tests.

import Foundation

/// One end of a runway: the threshold an aircraft lands on and the direction it lands or takes off in.
struct RunwayEnd: Equatable, Sendable {
    /// Designator painted on this end ("28C", "01L", "36").
    let ident: String
    let threshold: GeoPoint
    /// Degrees true, from this threshold toward the opposite one.
    let heading: Double
}

/// A runway with both ends.
struct Runway: Equatable, Sendable {
    /// The lower-numbered end (OurAirports' "le").
    let low: RunwayEnd
    /// The higher-numbered end (OurAirports' "he").
    let high: RunwayEnd
    let lengthFt: Int?
    /// Threshold elevation in feet (the airport's when the runway's isn't published).
    let elevationFt: Double

    var ends: [RunwayEnd] { [low, high] }
    /// "10C/28C".
    var name: String { "\(low.ident)/\(high.ident)" }
}

/// An airport with the runways the approach analysis may consider.
struct AirportRunways: Equatable, Sendable {
    let airport: Airport
    let runways: [Runway]
}

/// Runways from OurAirports (public domain) for the airports in `airports.csv`, generated by
/// `scripts/update-runways.sh`.
///
/// The table (about 4,100 runways) is parsed on first use and kept in memory (a few hundred KB),
/// so the widget only pays for it if it asks for runways. When `runways.csv` isn't in the bundle
/// every lookup returns no runways.
enum RunwayDB {
    private final class BundleToken {}

    /// Runways by airport ICAO code.
    private static let byICAO: [String: [Runway]] = load()

    /// ICAO codes by IATA code, built on first IATA lookup.
    private static let icaoByIATA: [String: String] = Dictionary(
        byICAO.keys.compactMap { icao in AirportDB.airport(code: icao).map { ($0.code, icao) } },
        uniquingKeysWith: { first, _ in first })

    /// Runways at the airport with this ICAO (4-letter) or IATA (3-letter) code.
    static func runways(code raw: String) -> [Runway] {
        let code = raw.trimmingCharacters(in: .whitespaces).uppercased()
        if let runways = byICAO[code] { return runways }
        return icaoByIATA[code].flatMap { byICAO[$0] } ?? []
    }

    /// Airports with a runway threshold within `nm` of `p`, nearest first.
    static func airports(near p: GeoPoint, within nm: Double) -> [AirportRunways] {
        let latWindow = nm / 60 + 0.1
        var found: [(AirportRunways, Double)] = []
        for (icao, runways) in byICAO {
            let distance = runways.flatMap(\.ends)
                .filter { abs($0.threshold.lat - p.lat) <= latWindow }
                .map { FlightService.gcDistance(p.lat, p.lon, $0.threshold.lat, $0.threshold.lon) }
                .min() ?? .infinity
            guard distance <= nm else { continue }
            let first = runways[0].low.threshold
            let airport = AirportDB.airport(code: icao) ?? Airport(code: icao, city: "", lat: first.lat, lon: first.lon)
            found.append((AirportRunways(airport: airport, runways: runways), distance))
        }
        return found.sorted { $0.1 < $1.1 }.map(\.0)
    }

    /// Parses `runways.csv`: `#` comment lines, then
    /// `icao,le_ident,le_lat,le_lon,le_hdg,he_ident,he_lat,he_lon,he_hdg,length_ft,elevation_ft`.
    static func parse(_ text: String) -> [String: [Runway]] {
        var table: [String: [Runway]] = [:]
        for line in text.split(separator: "\n") where !line.hasPrefix("#") {
            let c = line.split(separator: ",", omittingEmptySubsequences: false)
            guard c.count == 11,
                  let leLat = Double(c[2]), let leLon = Double(c[3]), let leHdg = Double(c[4]),
                  let heLat = Double(c[6]), let heLon = Double(c[7]), let heHdg = Double(c[8]),
                  let elevation = Double(c[10]), !c[0].isEmpty, !c[1].isEmpty, !c[5].isEmpty else { continue }
            let runway = Runway(low: RunwayEnd(ident: String(c[1]), threshold: GeoPoint(lat: leLat, lon: leLon), heading: leHdg),
                                high: RunwayEnd(ident: String(c[5]), threshold: GeoPoint(lat: heLat, lon: heLon), heading: heHdg),
                                lengthFt: Int(c[9]), elevationFt: elevation)
            table[String(c[0]), default: []].append(runway)
        }
        return table
    }

    private static func load() -> [String: [Runway]] {
        guard let url = Bundle(for: BundleToken.self).url(forResource: "runways", withExtension: "csv"),
              let text = try? String(contentsOf: url, encoding: .utf8) else {
            fdLog.error("runways.csv is missing from the bundle")
            return [:]
        }
        return parse(text)
    }
}

extension ApproachAnalyzer {
    /// An analyzer using the bundled runways of airports within 25 nm of `position`, plus the
    /// origin's and destination's wherever they are (for departure runways and preference).
    init(around position: GeoPoint, origin: Airport?, destination: Airport?) {
        var airports: [AirportRunways] = []
        for known in [destination, origin].compactMap({ $0 }) where !airports.contains(where: { $0.airport.code == known.code }) {
            let runways = RunwayDB.runways(code: known.code)
            if !runways.isEmpty { airports.append(AirportRunways(airport: known, runways: runways)) }
        }
        for nearby in RunwayDB.airports(near: position, within: Self.searchRadiusNM)
        where !airports.contains(where: { $0.airport.code == nearby.airport.code }) {
            airports.append(nearby)
        }
        self.init(airports: airports, origin: origin, destination: destination)
    }
}
